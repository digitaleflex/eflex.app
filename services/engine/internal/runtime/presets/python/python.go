// Package python renders the safe production Dockerfile for the Python runtime
// preset (FastAPI, Flask, Django installed with pip from a requirements.txt).
//
// Safety properties, mirrored from the Node preset (#121):
//   - The base image is a pinned constant (python:<minor>-slim-bookworm).
//   - Dependencies install from requirements.txt in their own layer, before the
//     source is copied, so rebuilds reuse the cache until the requirements change.
//   - The application runs as a non-root user; Python writes no bytecode and
//     does not buffer its output.
//   - The template is fully determined by its inputs: the same inputs always
//     produce the same Dockerfile. Commands are refused when they could leave
//     their own Dockerfile instruction (line breaks, trailing backslash).
package python

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"strings"

	"github.com/digitaleflex/axiom/services/engine/internal/runtime/presets"
)

// BaseImage is the pinned interpreter image.
const BaseImage = "python:" + presets.PythonVersion + "-slim-bookworm"

// Facts are the resolved commands the plan carries (not raw repository facts).
type Facts struct {
	BuildCommand string // installs the dependencies, e.g. "pip install -r requirements.txt"
	StartCommand string // starts the server and listens on Port
	Port         int
}

// ErrInvalid is returned when the facts cannot produce a safe Dockerfile.
var ErrInvalid = errors.New("python preset: invalid input")

func checkCommand(name, cmd string) error {
	if strings.TrimSpace(cmd) == "" {
		return fmt.Errorf("%w: %s is required", ErrInvalid, name)
	}
	if strings.ContainsAny(cmd, "\n\r\x00") || strings.HasSuffix(strings.TrimRight(cmd, " \t"), `\`) {
		return fmt.Errorf("%w: %s must be a single line that does not end with a backslash", ErrInvalid, name)
	}
	return nil
}

// Dockerfile renders the multi-stage-free, cache-friendly Dockerfile for the facts.
func Dockerfile(f Facts) (string, error) {
	if err := checkCommand("build command", f.BuildCommand); err != nil {
		return "", err
	}
	if err := checkCommand("start command", f.StartCommand); err != nil {
		return "", err
	}
	if f.Port < 1 || f.Port > 65535 {
		return "", fmt.Errorf("%w: port %d is out of range", ErrInvalid, f.Port)
	}

	// CMD in exec form is JSON: encode it properly instead of quoting by hand.
	var cmd bytes.Buffer
	enc := json.NewEncoder(&cmd)
	enc.SetEscapeHTML(false)
	if err := enc.Encode([]string{"sh", "-c", f.StartCommand}); err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString("# Generated by Axiom — safe production Python preset. Do not edit.\n")
	fmt.Fprintf(&b, "FROM %s\n", BaseImage)
	b.WriteString("ENV PYTHONDONTWRITEBYTECODE=1 \\\n")
	b.WriteString("    PYTHONUNBUFFERED=1 \\\n")
	b.WriteString("    PIP_NO_CACHE_DIR=1 \\\n")
	b.WriteString("    PIP_DISABLE_PIP_VERSION_CHECK=1\n")
	b.WriteString("WORKDIR /app\n")
	b.WriteString("COPY requirements.txt ./\n")
	fmt.Fprintf(&b, "RUN %s\n", f.BuildCommand)
	b.WriteString("COPY . .\n")
	b.WriteString("RUN useradd --create-home --uid 10001 axiom && chown -R axiom:axiom /app\n")
	b.WriteString("USER axiom\n")
	fmt.Fprintf(&b, "EXPOSE %d\n", f.Port)
	fmt.Fprintf(&b, "CMD %s", cmd.String())
	return b.String(), nil
}
