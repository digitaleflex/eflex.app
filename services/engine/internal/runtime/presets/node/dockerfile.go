package node

import (
	"fmt"
	"strings"

	"github.com/digitaleflex/axiom/services/engine/internal/runtime/presets"
)

// DockerfileForFacts renders the safe multi-stage Dockerfile for the facts.
// The template is fully determined by the facts: the same facts always
// produce the same Dockerfile.
func DockerfileForFacts(f Facts) (string, error) {
	p, err := Resolve(f)
	if err != nil {
		return "", err
	}
	if p.Runtime == RuntimeStatic {
		return staticDockerfile(f, p), nil
	}
	return nodeDockerfile(f, p), nil
}

// depsInstall installs all dependencies (including dev) in the deps stage.
// The lockfile-aware commands keep builds reproducible.
func depsInstall(pm string, hasLockfile bool) string {
	switch pm {
	case presets.PackageManagerNPM:
		if hasLockfile {
			return "npm ci"
		}
		return "npm install"
	case presets.PackageManagerPNPM:
		if hasLockfile {
			return "pnpm install --frozen-lockfile"
		}
		return "pnpm install"
	case presets.PackageManagerYarn:
		if hasLockfile {
			return "yarn install --frozen-lockfile"
		}
		return "yarn install"
	case presets.PackageManagerBun:
		if hasLockfile {
			return "bun install --frozen-lockfile"
		}
		return "bun install"
	default:
		return "npm ci"
	}
}

// prodInstall installs production-only dependencies in the runtime stage.
func prodInstall(pm string, hasLockfile bool) string {
	switch pm {
	case presets.PackageManagerNPM:
		if hasLockfile {
			return "npm ci --omit=dev"
		}
		return "npm install --omit=dev"
	case presets.PackageManagerPNPM:
		if hasLockfile {
			return "pnpm install --frozen-lockfile --prod"
		}
		return "pnpm install --prod"
	case presets.PackageManagerYarn:
		if hasLockfile {
			return "yarn install --frozen-lockfile --production"
		}
		return "yarn install --production"
	default: // bun
		if hasLockfile {
			return "bun install --frozen-lockfile --production"
		}
		return "bun install --production"
	}
}

// lockfileName is the canonical lockfile of each package manager.
func lockfileName(pm string) string {
	switch pm {
	case presets.PackageManagerNPM:
		return "package-lock.json"
	case presets.PackageManagerPNPM:
		return "pnpm-lock.yaml"
	case presets.PackageManagerYarn:
		return "yarn.lock"
	default: // bun
		return "bun.lockb"
	}
}

// pmSetup enables a package manager that is not bundled with the Node image.
// pnpm and yarn ship through Corepack; bun is installed with npm.
func pmSetup(pm string) string {
	switch pm {
	case presets.PackageManagerPNPM, presets.PackageManagerYarn:
		return "RUN corepack enable\n"
	case presets.PackageManagerBun:
		return "RUN npm install -g bun\n"
	default:
		return ""
	}
}

// nodeDockerfile renders the multi-stage Dockerfile for Next.js, Nuxt, Remix,
// SolidStart, RedwoodJS and generic Node.js applications: deps → build →
// minimal runtime.
func nodeDockerfile(f Facts, p NodePreset) string {
	var b strings.Builder
	b.WriteString("# Generated by Axiom (#121) — safe production Node preset. Do not edit.\n")
	fmt.Fprintf(&b, "FROM %s AS deps\n", Node20Alpine)
	b.WriteString("WORKDIR /app\n")
	b.WriteString(pmSetup(p.PackageManager))
	writeManifestCopy(&b, f, p.PackageManager)
	fmt.Fprintf(&b, "RUN %s\n", depsInstall(p.PackageManager, f.HasLockfile))

	fmt.Fprintf(&b, "\nFROM %s AS build\n", Node20Alpine)
	b.WriteString("WORKDIR /app\n")
	b.WriteString(pmSetup(p.PackageManager))
	b.WriteString("COPY --from=deps /app/node_modules ./node_modules\n")
	b.WriteString("COPY . .\n")
	if p.BuildCommand != "" {
		fmt.Fprintf(&b, "RUN %s\n", p.BuildCommand)
	}

	fmt.Fprintf(&b, "\nFROM %s\n", Node20Alpine)
	b.WriteString("ENV NODE_ENV=production\n")
	fmt.Fprintf(&b, "ENV PORT=%d\n", p.Port)
	b.WriteString("WORKDIR /app\n")
	b.WriteString(pmSetup(p.PackageManager))
	if p.OutputDir != "" {
		// Minimal runtime: manifest, lockfile, build output, prod dependencies.
		b.WriteString("COPY --from=build /app/package.json ./\n")
		if f.HasLockfile {
			fmt.Fprintf(&b, "COPY --from=build /app/%s ./\n", lockfileName(p.PackageManager))
		}
		fmt.Fprintf(&b, "RUN %s\n", prodInstall(p.PackageManager, f.HasLockfile))
		fmt.Fprintf(&b, "COPY --from=build /app/%s ./%s\n", p.OutputDir, p.OutputDir)
	} else {
		// Generic Node: the whole application, dependencies pruned to production
		// unless the framework needs its CLI from devDependencies (RedwoodJS).
		b.WriteString("COPY --from=build /app ./\n")
		if !p.KeepDevDependencies {
			fmt.Fprintf(&b, "RUN %s\n", prodInstall(p.PackageManager, f.HasLockfile))
		}
	}
	b.WriteString("USER node\n")
	fmt.Fprintf(&b, "EXPOSE %d\n", p.Port)
	fmt.Fprintf(&b, "CMD [\"sh\", \"-c\", %s]\n", shellQuote(p.StartCommand))
	return b.String()
}

// staticDockerfile renders the multi-stage Dockerfile for static frameworks
// (Vite, Astro, SvelteKit static): deps → build → static output served by
// nginx on the resolved port.
func staticDockerfile(f Facts, p NodePreset) string {
	var b strings.Builder
	b.WriteString("# Generated by Axiom — safe production static preset. Do not edit.\n")
	fmt.Fprintf(&b, "FROM %s AS deps\n", Node20Alpine)
	b.WriteString("WORKDIR /app\n")
	b.WriteString(pmSetup(p.PackageManager))
	writeManifestCopy(&b, f, p.PackageManager)
	fmt.Fprintf(&b, "RUN %s\n", depsInstall(p.PackageManager, f.HasLockfile))

	fmt.Fprintf(&b, "\nFROM %s AS build\n", Node20Alpine)
	b.WriteString("WORKDIR /app\n")
	b.WriteString(pmSetup(p.PackageManager))
	b.WriteString("COPY --from=deps /app/node_modules ./node_modules\n")
	b.WriteString("COPY . .\n")
	if p.BuildCommand != "" {
		fmt.Fprintf(&b, "RUN %s\n", p.BuildCommand)
	}

	// Static output: nginx serves the build. The nginx master process needs
	// root to start and drops to the nginx worker user; there is no
	// HEALTHCHECK because minimal images ship without curl/wget — Axiom
	// probes health externally.
	fmt.Fprintf(&b, "\nFROM %s\n", NginxAlpine)
	fmt.Fprintf(&b, "COPY --from=build /app/%s /usr/share/nginx/html\n", p.OutputDir)
	lines := []string{
		"server {",
		fmt.Sprintf("    listen %d;", p.Port),
		"    server_name _;",
		"    root /usr/share/nginx/html;",
		"    index index.html;",
		"    location / {",
		"        try_files $uri $uri/ /index.html;",
		"    }",
		"}",
	}
	fmt.Fprintf(&b, "RUN printf '%%s\\n' %s > /etc/nginx/conf.d/default.conf\n", shellWords(lines))
	fmt.Fprintf(&b, "EXPOSE %d\n", p.Port)
	return b.String()
}

// shellWords single-quotes every line for a printf '%s\n' invocation.
func shellWords(lines []string) string {
	quoted := make([]string, len(lines))
	for i, line := range lines {
		quoted[i] = "'" + strings.ReplaceAll(line, "'", `'\''`) + "'"
	}
	return strings.Join(quoted, " ")
}

// writeManifestCopy copies package.json and, when present, the lockfile.
func writeManifestCopy(b *strings.Builder, f Facts, pm string) {
	if f.HasLockfile {
		fmt.Fprintf(b, "COPY package.json %s ./\n", lockfileName(pm))
	} else {
		b.WriteString("COPY package.json ./\n")
	}
}

func shellQuote(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
}
