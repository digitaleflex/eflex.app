package build

import (
	"fmt"
	"strings"

	"github.com/digitaleflex/axiom/services/engine/internal/runtime/presets"
	nodepresets "github.com/digitaleflex/axiom/services/engine/internal/runtime/presets/node"
	phppresets "github.com/digitaleflex/axiom/services/engine/internal/runtime/presets/php"
	pythonpresets "github.com/digitaleflex/axiom/services/engine/internal/runtime/presets/python"
)

// Dockerfile templates for source-build presets. Node/Next.js/Vite templates
// are rendered by the safe runtime presets (#121): multi-stage, pinned base
// images, lockfile-aware installs, non-root user, NODE_ENV=production. PHP is
// rendered by the php preset (php-fpm + nginx + supervisor in one container).
// The Go template is refined with #122.
func dockerfileForPreset(preset, buildCommand, startCommand string, port int, outputDir, sourceDir string) (string, error) {
	switch preset {
	case "nextjs", "node", "nuxt", "remix", "solidstart", "redwoodjs", "vite", "astro", "sveltekit":
		// Vite is always served as static output: its plan has no start command.
		start := startCommand
		if preset == "vite" {
			start = ""
		}
		facts := nodepresets.Facts{
			PackageManager: inferPackageManager(buildCommand, start),
			HasBuildScript: buildCommand != "",
			HasStartScript: start != "",
			Framework:      frameworkForPreset(preset),
			Adapter:        adapterForPreset(preset, start),
			Port:           port,
			HasLockfile:    true,
			BuildCommand:   buildCommand,
			StartCommand:   start,
		}
		df, err := nodepresets.DockerfileForFacts(facts)
		if err != nil {
			return "", err
		}
		return df, nil
	case "python":
		return pythonpresets.Dockerfile(pythonpresets.Facts{BuildCommand: buildCommand, StartCommand: startCommand, Port: port})
	case "php", "laravel":
		return phppresets.Dockerfile(phppresets.Detect(sourceDir), buildCommand, startCommand, port)
	case "go":
		return fmt.Sprintf(`# Generated by Axiom for the go preset. Refined by #121.
FROM golang:1.23-alpine
WORKDIR /app
COPY . .
RUN %s
EXPOSE %d
CMD ["sh", "-c", %s]
`, shellQuote(buildCommand), port, shellQuote(startCommand)), nil
	default:
		return "", fmt.Errorf("no Dockerfile template for preset %q", preset)
	}
}

// inferPackageManager detects the package manager from the resolved commands
// (the plan carries commands, not the raw facts). Defaults to npm.
func inferPackageManager(commands ...string) string {
	for _, c := range commands {
		switch {
		case strings.HasPrefix(c, "pnpm"):
			return presets.PackageManagerPNPM
		case strings.HasPrefix(c, "yarn"):
			return presets.PackageManagerYarn
		case strings.HasPrefix(c, "bun"):
			return presets.PackageManagerBun
		case strings.HasPrefix(c, "npm"), strings.HasPrefix(c, "npx"):
			return presets.PackageManagerNPM
		}
	}
	return presets.PackageManagerNPM
}

func frameworkForPreset(preset string) string {
	switch preset {
	case "nextjs":
		return presets.FrameworkNextJS
	case "nuxt":
		return presets.FrameworkNuxt
	case "remix":
		return presets.FrameworkRemix
	case "solidstart":
		return presets.FrameworkSolidStart
	case "redwoodjs":
		return presets.FrameworkRedwoodJS
	case "vite":
		return presets.FrameworkVite
	case "astro":
		return presets.FrameworkAstro
	case "sveltekit":
		return presets.FrameworkSvelteKit
	}
	return ""
}

// adapterForPreset recovers the Astro/SvelteKit rendering mode from the plan:
// a start command means the sensitive framework is served by Node, its absence
// means static output.
func adapterForPreset(preset, startCommand string) string {
	switch preset {
	case "astro", "sveltekit":
		if startCommand != "" {
			return presets.AdapterNode
		}
		return presets.AdapterStatic
	}
	return ""
}

func shellQuote(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
}
